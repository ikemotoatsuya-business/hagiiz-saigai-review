HEAD_FILL = PatternFill("solid", fgColor="1F3864")
NEW_FILL = PatternFill("solid", fgColor="FDE7F1")


def headers(ws):
    return [c.value for c in ws[1]]


def style_new_header(ws, col):
    c = ws.cell(row=1, column=col)
    c.fill = NEW_FILL
    c.font = Font(bold=True, color="000000")
    c.alignment = Alignment(wrap_text=True, vertical="top")


def add_cols(ws, names):
    h = headers(ws)
    for n in names:
        if n not in h:
            ws.cell(row=1, column=len(h) + 1, value=n)
            style_new_header(ws, len(h) + 1)
            h.append(n)


def row_by_id(ws, key):
    for r in range(2, ws.max_row + 1):
        if ws.cell(row=r, column=1).value == key:
            return r
    return None


def upsert(ws, rec):
    h = {n: i + 1 for i, n in enumerate(headers(ws))}
    key = rec[headers(ws)[0]]
    r = row_by_id(ws, key) or ws.max_row + 1
    for k, v in rec.items():
        ws.cell(row=r, column=h[k], value=v)


def add_pairs(ws, pairs, extra=None):
    have = {(ws.cell(row=r, column=1).value, ws.cell(row=r, column=2).value) for r in range(2, ws.max_row + 1)}
    for a, b in pairs:
        if (a, b) not in have:
            ws.append([a, b] + ([extra] if extra else []))


def new_sheet(name, cols, rows, after, widths):
    if name in wb.sheetnames:
        del wb[name]
    ws = wb.create_sheet(name, index=wb.sheetnames.index(after) + 1)
    for i, c in enumerate(cols, 1):
        ws.cell(row=1, column=i, value=c)
        style_new_header(ws, i)
    for r in rows:
        ws.append([r.get(c, "") for c in cols])
    ws.freeze_panes = "B2"
    for i, w in enumerate(widths, 1):
        ws.column_dimensions[ws.cell(row=1, column=i).column_letter].width = w
    return ws


